# التمرين الثاني: الشروط (if / else)
# المستوى: مبتدئ
# البرنامج بيسألك عن عمرك وبيرد عليك حسب الإجابة

age = int(input("عندك كام سنة؟ "))

if age < 13:
    print("لسه صغير! بايثون هتعجبك جدًا 🎈")
elif age < 20:
    print("سن مثالي تبدأ فيه البرمجة 💪")
else:
    print("مفيش سن متأخر للتعلم، أنت في الطريق الصح 🚀")

